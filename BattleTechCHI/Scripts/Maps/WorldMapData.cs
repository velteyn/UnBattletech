    public void Initialize()
    {
        Array.Copy(PacificaIsland, _tiles, 4096);
        _visibility = new byte[2048];
        GD.Print("WorldMapData initialized (Pacifica island template)");
    }

    /// <summary>
    /// Ottiene il tile ID a una data posizione world map.
    /// </summary>
    public byte GetTile(int x, int y)
    {
        if (x < 0 || x >= 64 || y < 0 || y >= 64) return 0;
        return _tiles[y * 64 + x];
    }

    /// <summary>
    /// Imposta il tile ID a una data posizione.
    /// </summary>
    public void SetTile(int x, int y, byte tileId)
    {
        if (x < 0 || x >= 64 || y < 0 || y >= 64) return;
        _tiles[y * 64 + x] = tileId;
    }

    /// <summary>
    /// Carica i tile dal template raw (64×64 = 4096 byte).
    /// </summary>
    public void LoadTiles(byte[] tileData)
    {
        if (tileData.Length >= 4096)
            Array.Copy(tileData, _tiles, 4096);
    }

    /// <summary>
    /// Verifica se un tile è acqua (tile ID 0x00).
    /// </summary>
    public bool IsWater(int x, int y) => GetTile(x, y) == 0x00;

    /// <summary>
    /// Verifica se una posizione è passabile (non acqua e non bloccata).
    /// </summary>
    public bool IsWalkable(int x, int y)
    {
        if (x < 0 || x >= 64 || y < 0 || y >= 64) return false;
        byte tile = GetTile(x, y);
        // Water (0x00) è bloccante
        if (tile == 0x00) return false;
        // TODO: verificare proprietà tile da 0x7AD (LoS blocking)
        return true;
    }

    /// <summary>
    /// Restituisce il nome del POI più vicino o stringa vuota.
    /// </summary>
    public string GetNearestPoiName(int x, int y, int radius = 3)
    {
        foreach (var (px, py, name) in PoiLocations)
        {
            if (Mathf.Abs(x - px) <= radius && Mathf.Abs(y - py) <= radius)
                return name;
        }
        return "";
    }

    /// <summary>
    /// Controlla/aggiorna la visibilità per una data posizione world map.
    /// </summary>
    public bool IsVisible(int worldX, int worldY)
    {
        // 128×128 bit-packed: 2×2 visibility bit per world map tile
        int bitIdx = worldY * 2 * 128 + worldX * 2;
        int byteIdx = bitIdx / 8;
        int bitInByte = bitIdx % 8;
        if (byteIdx < 0 || byteIdx >= _visibility.Length) return false;
        return (_visibility[byteIdx] & (1 << bitInByte)) != 0;
    }

    /// <summary>
    /// Imposta la visibilità per una data posizione.
    /// </summary>
    public void SetVisible(int worldX, int worldY, bool visible)
    {
        int bitIdx = worldY * 2 * 128 + worldX * 2;
        int byteIdx = bitIdx / 8;
        int bitInByte = bitIdx % 8;
        if (byteIdx < 0 || byteIdx >= _visibility.Length) return;
        if (visible)
            _visibility[byteIdx] |= (byte)(1 << bitInByte);
        else
            _visibility[byteIdx] &= (byte)~(1 << bitInByte);
    }
